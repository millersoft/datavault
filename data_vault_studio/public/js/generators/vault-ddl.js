function hubColumns(h){
  return [
    { name: hubKey(h.entity), type:hashSqlType(), notNull:true, hashed:true },
    { name: businessKeyColumnName(h.entity), type:'TEXT', notNull:false },
    { name: 'load_dts', type:'TIMESTAMP', notNull:false },
    { name: 'record_source_id', type:'INT', notNull:false },
    { name: 'tenant_id', type:'VARCHAR(20)', notNull:true },
  ];
}
function linkColumns(l){
  const cols = [{ name: linkKeyOf(l.entity), type:hashSqlType(), notNull:true, hashed:true }];
  l.hubs.forEach(h=>{
    const hub = findHub(h.hubId);
    if (hub) cols.push({ name: linkHubKeyColumnName(l, h), type:hashSqlType(), notNull:true, hashed:true });
  });
  cols.push({ name:'load_dts', type:'TIMESTAMP', notNull:false });
  cols.push({ name:'record_source_id', type:'INT', notNull:false });
  cols.push({ name:'tenant_id', type:'VARCHAR(20)', notNull:true });
  return cols;
}
function hubSatColumns(s){
  const hub = findHub(s.hubId);
  const cols = [
    { name:'sat_key', type:'BYTEA', notNull:true, hashed:true },
    { name: hubKey(hub.entity), type:hashSqlType(), notNull:true, hashed:true },
    { name:'load_dts', type:'TIMESTAMP', notNull:false },
    { name:'load_end_dts', type:'TIMESTAMP', notNull:false },
    { name:'record_source_id', type:'INT', notNull:false },
  ];
  s.attrs.forEach(a=> cols.push({ name:a.target, type:satelliteAttributeType(s,a), notNull:false }));
  cols.push({ name:'sat_attributes_concat', type:'BYTEA', notNull:false, hashed:true });
  cols.push({ name:'tenant_id', type:'VARCHAR(20)', notNull:true });
  return cols;
}
function linkSatColumns(s){
  const link = findLink(s.linkId);
  const cols = [
    { name:'sat_key', type:'BYTEA', notNull:true, hashed:true },
    { name: linkKeyOf(link.entity), type:hashSqlType(), notNull:true, hashed:true },
  ];
  cols.push({ name:'load_dts', type:'TIMESTAMP', notNull:false });
  cols.push({ name:'load_end_dts', type:'TIMESTAMP', notNull:false });
  cols.push({ name:'record_source_id', type:'INT', notNull:false });
  s.attrs.forEach(a=> cols.push({ name:a.target, type:satelliteAttributeType(s,a), notNull:false }));
  cols.push({ name:'sat_attributes_concat', type:'BYTEA', notNull:false, hashed:true });
  cols.push({ name:'tenant_id', type:'VARCHAR(20)', notNull:true });
  return cols;
}

// Older Studio DDL incorrectly duplicated every parent Hub hash on a Link
// Satellite. The Hop loader uses those hashes to find the parent Link, then
// inserts only that Link's key into the satellite. Keeping the duplicated Hub
// columns as NOT NULL therefore rejects every row. Track the exact legacy
// columns so an already-deployed Studio schema can be repaired deliberately.
function legacyLinkSatHubColumns(s){
  const link = findLink(s.linkId);
  if (!link) return [];
  return link.hubs.map(h=>linkHubKeyColumnName(link, h)).filter(Boolean);
}

function buildDataVaultLocalSupportDdl(){
  const parts = [`-- =========================================================\n-- LOCAL DATA VAULT SUPPORT DDL — schema: data_vault\n-- Generated by Data Vault Studio\n-- Core hub/link/sat/lsat relations are created separately as foreign tables.\n-- =========================================================\n`];
  parts.push('CREATE SCHEMA IF NOT EXISTS data_vault;');
  parts.push(schemaOwnershipFixSql('data_vault', 'data_vault'));
  parts.push('');
  parts.push('SET ROLE data_vault;');
  parts.push('');
  externalCoreTableSpecs().forEach(spec=>{
    parts.push(`-- Local error table for ${spec.family}: ${spec.name}`);
    parts.push(ddlFromColumns(`data_vault.${spec.name}_err`, buildErrColumns(spec.columns)));
    parts.push(`ALTER TABLE data_vault.${spec.name}_err OWNER TO data_vault;`);
    parts.push('');
  });
  parts.push(`-- Verification view remains local PostgreSQL`);
  parts.push(`CREATE OR REPLACE VIEW data_vault.vw_information_schema_columns_data_vault AS\nSELECT table_name, table_schema, column_name, ordinal_position, is_nullable, data_type\nFROM information_schema.columns\nWHERE table_schema = 'data_vault';`);
  parts.push(`ALTER VIEW data_vault.vw_information_schema_columns_data_vault OWNER TO data_vault;`);
  parts.push('RESET ROLE;');
  return parts.join('\n');
}

function buildFdwInfrastructureDdl(){
  return [
    `-- =========================================================`,
    `-- POSTGRESQL JDBC_FDW INFRASTRUCTURE`,
    `-- Run after the physical target tables have been created and verified.`,
    `-- =========================================================`,
    '',
    buildFdwPreamble(),
  ].join('\n');
}

function buildFdwForeignTablesDdl(){
  const parts = [
    `-- =========================================================`,
    `-- LOCAL FOREIGN TABLES — CREATED LAST`,
    `-- Generated by Data Vault Studio`,
    `-- =========================================================`,
    '',
    'SET ROLE data_vault;',
    '',
  ];
  externalCoreTableSpecs().forEach(spec=>{
    parts.push(`-- ${spec.family.toUpperCase()}: ${spec.name}`);
    parts.push(ddlForeignTable(`data_vault.${spec.name}`, spec.columns, spec.keyColumn));
    parts.push(`ALTER FOREIGN TABLE data_vault.${spec.name} OWNER TO data_vault;`);
    parts.push('');
  });
  parts.push(crossRoleGrantsSql('data_vault', 'data_vault', ['pdi_meta', 'staging']));
  parts.push('RESET ROLE;');
  return parts.join('\n');
}

function buildDataVaultDdl(){
  if (state.externalTables.enabled){
    return [
      buildDataVaultLocalSupportDdl(),
      buildFdwInfrastructureDdl(),
      buildFdwForeignTablesDdl(),
    ].join('\n\n');
  }

  const parts = [`-- =========================================================\n-- DATA VAULT DDL — schema: data_vault\n-- Generated by Data Vault Studio\n-- =========================================================\n`];
  parts.push('CREATE SCHEMA IF NOT EXISTS data_vault;');
  parts.push(schemaOwnershipFixSql('data_vault', 'data_vault'));
  parts.push('');
  parts.push('SET ROLE data_vault;');
  parts.push('');

  externalCoreTableSpecs().forEach(spec=>{
    parts.push(`-- ${spec.family.toUpperCase()}: ${spec.name}`);
    parts.push(ddlFromColumns(`data_vault.${spec.name}`, spec.columns));
    parts.push(`ALTER TABLE data_vault.${spec.name} OWNER TO data_vault;`);
    parts.push(...hashedColumnIndexStatements(`data_vault.${spec.name}`, spec.columns));
    parts.push(ddlFromColumns(`data_vault.${spec.name}_err`, buildErrColumns(spec.columns)));
    parts.push(`ALTER TABLE data_vault.${spec.name}_err OWNER TO data_vault;`);
    parts.push('');
  });

  parts.push(`-- Verification view (create only if missing/wrong)`);
  parts.push(`CREATE OR REPLACE VIEW data_vault.vw_information_schema_columns_data_vault AS\nSELECT table_name, table_schema, column_name, ordinal_position, is_nullable, data_type\nFROM information_schema.columns\nWHERE table_schema = 'data_vault';`);
  parts.push(`ALTER VIEW data_vault.vw_information_schema_columns_data_vault OWNER TO data_vault;`);
  parts.push('');
  parts.push(crossRoleGrantsSql('data_vault', 'data_vault', ['pdi_meta', 'staging']));
  parts.push('RESET ROLE;');
  return parts.join('\n');
}
